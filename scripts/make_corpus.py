_norm = lambda s: re.sub(r"[^\w\u4e00-\u9fff]+", "", s.lower()) # noqa: E731


def _doc_text(doc: dict) -> str:
    parts = [doc["title"]]
    for it in doc["items"]:
        parts.append(it[1] if it[0] in ("h1", "h2", "p") else render_table(it[1], it[2]))
    return "\n".join(parts)


def _register_font():
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    for name, path in [("SimHei", r"C:\Windows\Fonts\simhei.ttf"),
                       ("MSYaHei", r"C:\Windows\Fonts\msyh.ttc"),
                       ("SimSun", r"C:\Windows\Fonts\simsun.ttc")]:
        try:
            kw = {"subfontIndex": 0} if path.endswith(".ttc") else {}
            pdfmetrics.registerFont(TTFont(name, path, **kw))
            return name
        except Exception: # noqa: BLE001
            continue
    raise RuntimeError("未找到可用中文字体")


def _render_pdf(doc: dict, out: Path):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    font = _register_font()
    h1 = ParagraphStyle("h1", fontName=font, fontSize=16, leading=24, spaceBefore=14, spaceAfter=6)
    h2 = ParagraphStyle("h2", fontName=font, fontSize=13, leading=20, spaceBefore=10, spaceAfter=4)
    body = ParagraphStyle("body", fontName=font, fontSize=10.5, leading=19, firstLineIndent=21)
    story = [Paragraph(doc["title"], ParagraphStyle("t", fontName=font, fontSize=20, leading=28, spaceAfter=10)),
             Spacer(1, 4 * mm)]
    for it in doc["items"]:
        if it[0] == "h1":
            story.append(Paragraph(it[1], h1))
        elif it[0] == "h2":
            story.append(Paragraph(it[1], h2))
        elif it[0] == "p":
            story.append(Paragraph(it[1], body))
        else:
            header, rows = it[1], it[2]
            data = [header] + rows
            t = Table(data, repeatRows=1, colWidths=[(170 / len(header)) * mm] * len(header))
            t.setStyle(TableStyle([
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                ("FONTNAME", (0, 0), (-1, -1), font), ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]))
            story.append(t)
            story.append(Spacer(1, 3 * mm))
    SimpleDocTemplate(str(out), pagesize=A4, topMargin=20 * mm, bottomMargin=20 * mm).build(story)


def _render_docx(doc: dict, out: Path):
    import docx

    d = docx.Document()
    d.add_heading(doc["title"], 0)
    for it in doc["items"]:
        if it[0] == "h1":
            d.add_heading(it[1], 1)
        elif it[0] == "h2":
            d.add_heading(it[1], 2)
        elif it[0] == "p":
            d.add_paragraph(it[1])
        else:
            header, rows = it[1], it[2]
            table = d.add_table(rows=1, cols=len(header))
            table.style = "Table Grid"
            for i, h in enumerate(header):
                table.rows[0].cells[i].text = h
            for r in rows:
                cells = table.add_row().cells
                for i, c in enumerate(r):
                    cells[i].text = c
    d.save(str(out))


def _render_txt(doc: dict, out: Path):
    parts = [doc["title"], ""]
    for it in doc["items"]:
        if it[0] in ("h1", "h2"):
            parts += ["", it[1]]
        elif it[0] == "p":
            parts += [it[1]]
        else:
            parts += [render_table(it[1], it[2])]
    out.write_text("\n".join(parts), encoding="utf-8")


def _render_md(doc: dict, out: Path):
    parts = [f" # {doc['title']}"]
    for it in doc["items"]:
        if it[0] == "h1":
            parts += ["", f" # # {it[1]}"]
        elif it[0] == "h2":
            parts += ["", f" # # # {it[1]}"]
        elif it[0] == "p":
            parts += ["", it[1]]
        else:
            header, rows = it[1], it[2]
            parts += ["", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
            parts += ["| " + " | ".join(r) + " |" for r in rows]
    out.write_text("\n".join(parts), encoding="utf-8")


RENDERERS = {"pdf": _render_pdf, "docx": _render_docx, "txt": _render_txt, "md": _render_md}


def main():
    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    texts: dict[str, str] = {}
    print("生成语料文档...")
    for doc in DOCS:
        out = CORPUS_DIR / doc["file"]
        RENDERERS[doc["fmt"]](doc, out)
        texts[doc["file"]] = _doc_text(doc)
        print(f"  ✅ {doc['file']}（{doc['type']}）")

    questions, qid = [], 0

    def add(q, answer, doc, section, answerable, history=None, qtype=None, gold=None):
        nonlocal qid
        qid += 1
        questions.append({
            "id": qid, "question": q,
            "gold_answer": answer, "gold_doc": doc, "gold_section": section,
            "answerable": answerable,
            "doc_type": next(d["type"] for d in DOCS if d["file"] == doc),
            "multi_turn": bool(history), "history": history or [],
            "qtype": qtype or ("multi_turn" if history else ("single" if answerable else "refusal")),
            **({"gold": gold} if gold else {}),
        })

    for doc_name, facts in FACTS.items():
        for q, spans, section in facts:
            add(q, "；".join(spans), doc_name, section, True)
    for q, history, spans, doc, section in MULTI_TURN:
        add(q, "；".join(spans), doc, section, True, history=history)
    for q, gold_items in MULTI_HOP:
        doc0 = gold_items[0]["doc"]
        answer = "；".join(s for g in gold_items for s in g["spans"])
        add(q, answer, doc0, "", True, qtype="multi_hop", gold=gold_items)
    for q, span, doc, section in PARAPHRASE:
        add(q, span, doc, section, True, qtype="paraphrase")
    for q, span, doc, section in ADVERSARIAL:
        add(q, span, doc, section, True, qtype="adversarial")
    for q, doc in REFUSALS:
        add(q, "（知识库中未提及，应拒答）", doc, "", False)

    # ---- 金标校验：所有 span 必须是对应文档文本的子串 ----
    n_bad = 0
    for item in questions:
        if not item["answerable"]:
            continue
        if item.get("qtype") == "multi_hop":
            # 多跳题：每个金标片段按其所属文档分别校验
            for g in item["gold"]:
                for sp in filter(None, (_norm(s) for s in g["spans"])):
                    if sp not in _norm(texts[g["doc"]]):
                        print(f"❌ 金标片段不在文档中: [{item['id']}] {item['question']} :: {sp[:50]}")
                        n_bad += 1
        else:
            for sp in filter(None, (_norm(s) for s in item["gold_answer"].split("；"))):
                if sp not in _norm(texts[item["gold_doc"]]):
                    print(f"❌ 金标片段不在文档中: [{item['id']}] {item['question']} :: {sp[:50]}")
                    n_bad += 1
    if n_bad:
        sys.exit(f"共 {n_bad} 处金标校验失败，请修正")

    QUESTIONS_OUT.write_text(
        "\n".join(json.dumps(q, ensure_ascii=False) for q in questions), encoding="utf-8")
    n_a = sum(1 for q in questions if q["answerable"])
    n_r = len(questions) - n_a
    n_mt = sum(1 for q in questions if q.get("multi_turn"))
    by_type: dict[str, int] = {}
    for q in questions:
        by_type[q.get("qtype", "?")] = by_type.get(q.get("qtype", "?"), 0) + 1
    print(f"\n✅ 评测集 {QUESTIONS_OUT}")
    print(f"   共 {len(questions)} 题 = 可回答 {n_a}（多轮 {n_mt}）+ 拒答 {n_r}（占比 {n_r / len(questions):.1%}）")
    print(f"   题型分布: {json.dumps(by_type, ensure_ascii=False)}")


if __name__ == "__main__":
    main()
